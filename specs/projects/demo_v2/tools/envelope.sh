#!/usr/bin/env bash
# Write the voiceover beat's waveform: segments/v2-voiceover-sync/envelope.ts, the loudness of
# demo_v2's default track every 0.1s, and the SHA-256 of the track it read. Re-run after
# rebuilding the track; a test fails while the hash doesn't match track.mp3.
#
# Usage: envelope.sh [track.mp3]
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"

track="${1:-$DEMO_DIR/videos/demo_v2/audio/tracks/v1/track.mp3}"
out="$DEMO_DIR/segments/v2-voiceover-sync/envelope.ts"

ffmpeg -v error -i "$track" -ac 1 -ar 8000 -f s16le - | python3 -I -c '
import hashlib, math, struct, sys
data = sys.stdin.buffer.read()
with open(sys.argv[1], "rb") as f:
	sha = hashlib.sha256(f.read()).hexdigest()
samples = struct.unpack("<%dh" % (len(data) // 2), data)
rms = []
for i in range(0, len(samples), 800):  # 0.1s at 8 kHz
	chunk = samples[i:i + 800]
	rms.append(math.sqrt(sum(x * x for x in chunk) / len(chunk)))
peak = max(rms)
digits = "0123456789abcdefghijklmnopqrstuvwxyz"
# -40..0 dBFS (of the peak) onto 0..35.
levels = [max(0, min(35, round((20 * math.log10(v / peak + 1e-9) + 40) / 40 * 35))) for v in rms]
env = "".join(digits[v] for v in levels)
lines = [env[i:i + 90] for i in range(0, len(env), 90)]
print("// Generated by specs/projects/demo_v2/tools/envelope.sh from the default track")
print("// (audio/tracks/v1/track.mp3): its loudness every 0.1s, one base-36 digit each, 0..z for")
print("// -40..0 dB of the peak. Re-run the script after the track is rebuilt.")
print("")
print("/** One level (0-35) per 0.1s of the track. */")
print("export const ENVELOPE =")
for i, line in enumerate(lines):
	end = ";" if i == len(lines) - 1 else " +"
	print("\t\"%s\"%s" % (line, end))
print("")
print("export const ENVELOPE_STEP_S = 0.1;")
print("")
print("/** SHA-256 of the track this envelope was read from: a test fails once the track changes. */")
print("export const TRACK_SHA256 = \"%s\";" % sha)
' "$track" >"$out"
echo "$out"
