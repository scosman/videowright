#!/usr/bin/env node
// Computes every segment's advances, frame-exact, from the assembled narration's word times
// (audio/originals/voiceovers/assembled/), and writes audio/cues.json: the timing the track,
// the voiceover and the segments read. Run from the video folder after assemble.mjs:
//   node audio/sync.mjs
//
// The render fires a segment's advance a on frame start + round(a × 60), where start is the sum
// of the earlier segments' last advances (in frames). A cued advance lands 9 frames (0.150s)
// before its word's frame. Cue words are matched in order through the narration.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const FPS = 60;
const LEAD = 9;
const DIR = "audio/originals/voiceovers/assembled";
/** The Now clips' minimum hold after the sweep (s); the narration-sync pair's exit honours it. */
const MIN_NOW_HOLD = 4.0;

// Cues per segment: a word (anchored LEAD frames before it), or a rule:
//   { release: n }        n frames after the end of the word before the next word cue
//   { before: w, frames } `frames` before word w (not consumed: the next segment may cue it)
//   { end: true }         the narration's last frame (its 5s end hold is in the take)
const PLAN = [
	["fm-title", [{ release: 12 }, "In"]],
	["fm-pair-title-card", ["Now", "3D"]],
	["fm-pair-3d", ["Now", "Product"]],
	["fm-pair-product-ui", ["Now", "In"]],
	["fm-pair-narration-sync", ["Now", { before: "Previously", frames: 36 }]],
	["fm-voice", ["This", "Both"]],
	["fm-cta", ["VideoWrite", "open-source", "animation", "Download", { end: true }]],
];
/** Segments whose first advance is a Then → Now sweep (the whooshes land on these). */
const SWEEPS = [
	"fm-pair-title-card",
	"fm-pair-3d",
	"fm-pair-product-ui",
	"fm-pair-narration-sync",
	"fm-voice",
];

// Case-sensitive, so the cue "In" (a sentence start) never matches "in" mid-sentence.
const norm = (w) => w.replace(/[^A-Za-z0-9]/g, "");
const { words } = JSON.parse(readFileSync(`${DIR}/timing.json`, "utf8"));
const { pieces, standIn } = JSON.parse(readFileSync(`${DIR}/pieces.json`, "utf8"));
const seconds = Number(
	execFileSync(
		"ffprobe",
		["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", `${DIR}/audio.wav`],
		{
			encoding: "utf8",
		},
	),
);
const totalFrames = Math.round(seconds * FPS);
const frameOf = (t) => Math.round(t * FPS);

let cursor = 0;
const indexOf = (w, from = cursor) => {
	const i = words.findIndex((x, k) => k >= from && norm(x.word) === norm(w));
	if (i < 0) throw new Error(`no "${w}" after word ${from}`);
	return i;
};

const segments = {};
let start = 0;
for (const [id, cues] of PLAN) {
	const frames = cues.map((cue, c) => {
		if (typeof cue === "string") {
			const i = indexOf(cue);
			cursor = i + 1;
			return frameOf(words[i].start) - LEAD;
		}
		if ("release" in cue) {
			const next = cues.slice(c + 1).find((x) => typeof x === "string");
			const i = indexOf(next);
			return frameOf(words[i - 1].end) + cue.release;
		}
		if ("before" in cue) return frameOf(words[indexOf(cue.before)].start) - cue.frames;
		if (cue.end) return totalFrames;
		throw new Error(`bad cue ${JSON.stringify(cue)}`);
	});
	const rel = frames.map((f) => f - start);
	if (rel.some((f, k) => f <= (k ? rel[k - 1] : 0)))
		throw new Error(`${id}: advances not increasing: ${rel}`);
	segments[id] = {
		start: start / FPS,
		startFrame: start,
		advances: rel.map((f) => Math.round((f / FPS) * 1000) / 1000),
	};
	start = frames.at(-1);
}
if (start !== totalFrames)
	throw new Error(`the last segment ends at frame ${start}, the narration at ${totalFrames}`);

const sweeps = SWEEPS.map((id) => segments[id].start + segments[id].advances[0]);
const sync = segments["fm-pair-narration-sync"];
const hold = sync.advances[1] - sync.advances[0];
if (hold < MIN_NOW_HOLD)
	throw new Error(`the narration-sync Now clip holds ${hold.toFixed(2)}s (< ${MIN_NOW_HOLD})`);

const piece = (name) => pieces.find((p) => p.name === name);
const wordsOf = (name) => {
	const [a, b] = piece(name).words;
	return words.slice(a, b + 1);
};
const voice = {
	start: segments["fm-voice"].start,
	then: { words: wordsOf("voice_then") },
	now: { words: wordsOf("voice_now") },
};
const cues = {
	note: "Generated by audio/sync.mjs from the assembled narration. Do not edit.",
	standIn,
	fps: FPS,
	frames: totalFrames,
	duration: totalFrames / FPS,
	segments,
	sweeps,
	/** The narration's last word's end ("GitHub."): the end hold starts here. */
	lastWordEnd: words.at(-1).end,
	voice,
	music: {
		// Out over the cut into the voice beat; back after the voice beat's last word.
		outAt: voice.start,
		inAt: Math.round((voice.now.words.at(-1).end + 0.3) * 1000) / 1000,
	},
};
writeFileSync("audio/cues.json", `${JSON.stringify(cues, null, "\t")}\n`);
console.log(
	`${standIn ? "[stand-in opening] " : ""}${totalFrames} frames (${(totalFrames / FPS).toFixed(3)}s)`,
);
for (const [id, s] of Object.entries(segments))
	console.log(`  ${id.padEnd(24)} ${s.start.toFixed(3)}  [${s.advances.join(", ")}]`);
console.log(
	`  sweeps ${sweeps.map((t) => t.toFixed(3)).join(", ")}; narration-sync Now hold ${hold.toFixed(2)}s`,
);
