#!/usr/bin/env bash
# Writes segments/fm-voice/envelopes.ts: the loudness envelope (0-100, 30 per second) of the
# voice beat's two lines in the assembled narration, for its waveforms. Each window starts 0.15s
# before its line's first word (audio/cues.json) and ends 0.15s after its last.
# Run from examples/videowright_demo, after audio/assemble.mjs and audio/sync.mjs.
set -euo pipefail
VIDEO=videos/2026_11_five_months
WAV=$VIDEO/audio/originals/voiceovers/assembled/audio.wav
read -r T0 T1 N0 N1 < <(node -e '
const c = require("./'$VIDEO'/audio/cues.json");
const w = (l) => [l.words[0].start - 0.15, l.words.at(-1).end + 0.15].map((t) => t.toFixed(3));
console.log([...w(c.voice.thenLine), ...w(c.voice.nowLine)].join(" "));')
env_of() {
	ffmpeg -hide_banner -nostats -ss "$1" -to "$2" -i "$WAV" \
		-af "aresample=44100,asetnsamples=1470,astats=metadata=1:reset=1,ametadata=print:key=lavfi.astats.Overall.RMS_level:file=-" \
		-f null - 2>/dev/null |
		awk -F= '/RMS_level/{v=$2; if(v=="-inf")v=-90; a[n++]=(v<-60?0:int((v+60)*100/60))} END{for(i=0;i<n;i++) printf "%s%d", (i?", ":""), a[i]}'
}
{
	echo "// Generated by videos/2026_11_five_months/footage/voice_envelopes.sh. Do not edit."
	echo "// Loudness (0-100, RMS over -60..0 dBFS) at 30 values per second, from \`at\` (track s)."
	echo ""
	echo "/** The Asher v2 line. */"
	echo "export const THEN_ENVELOPE = { at: $T0, values: [$(env_of "$T0" "$T1")] };"
	echo ""
	echo "/** The Cosman-1 v4 line. */"
	echo "export const NOW_ENVELOPE = { at: $N0, values: [$(env_of "$N0" "$N1")] };"
} > segments/fm-voice/envelopes.ts
echo "wrote segments/fm-voice/envelopes.ts (then from ${T0}s, now from ${N0}s)"
