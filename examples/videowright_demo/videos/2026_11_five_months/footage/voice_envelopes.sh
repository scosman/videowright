#!/usr/bin/env bash
# Writes segments/fm-voice/envelopes.ts: the loudness envelope (0-100, 30 per second) of the
# voice beat's two lines, for its waveforms. Run from examples/videowright_demo.
#   Then: the Asher v2 line (its whole file, 5.4s).
#   Now:  the Cosman-1 v4 line, track 48.95-54.40s of the narration (audio/originals/voiceovers/v1).
set -euo pipefail
VO=videos/2026_11_five_months/audio/originals/voiceovers
env_of() {
	ffmpeg -hide_banner -nostats -ss "$2" -t "$3" -i "$1" \
		-af "aresample=44100,asetnsamples=1470,astats=metadata=1:reset=1,ametadata=print:key=lavfi.astats.Overall.RMS_level:file=-" \
		-f null - 2>/dev/null |
		awk -F= '/RMS_level/{v=$2; if(v=="-inf")v=-90; a[n++]=(v<-60?0:int((v+60)*100/60))} END{for(i=0;i<n;i++) printf "%s%d", (i?", ":""), a[i]}'
}
{
	echo "// Generated by videos/2026_11_five_months/footage/voice_envelopes.sh. Do not edit."
	echo "// Loudness (0-100, RMS over -60..0 dBFS) at 30 values per second."
	echo ""
	echo "/** The Asher v2 line, from the start of its file (placed at track 42.60s). */"
	echo "export const THEN_ENVELOPE = [$(env_of "$VO/then_asher_v2/audio.mp3" 0 5.4)];"
	echo ""
	echo "/** The Cosman-1 v4 line, from track 48.95s. */"
	echo "export const NOW_ENVELOPE = [$(env_of "$VO/v1/audio.mp3" 48.95 5.45)];"
} > segments/fm-voice/envelopes.ts
echo "wrote segments/fm-voice/envelopes.ts"
