import { defineSegment } from "videowright";
import { fontsReady } from "../../components/v2/fonts.js";
import { hideHud } from "../../components/v2/hud.js";
import {
	type Camera,
	type CameraKey,
	IDENTITY,
	type Ticker,
	cameraAt,
	createTicker,
	drawEase,
	expoOut,
	sineInOut,
} from "../../components/v2/motion.js";
import {
	type Terminal,
	createTerminal,
	rowY,
	spinnerGlyph,
	tui,
} from "../../components/v2/terminal.js";
import { COLD_OPEN, coldOpenCharTimes } from "../../components/v2/typing.js";

// Beat 1: a real Claude Code session, full bleed, no HUD. Cold and tight on the prompt as it
// types (the keys you see are the keys you hear), then the camera pulls back as Claude works,
// and "Video is ready" lands on "with a single prompt". The beat ends on the hard cut into the
// instrument world of the video Claude just made.
//
// The terminal is a TUI: lines appear whole and the layout redraws in place, as a terminal
// does; the camera carries the motion. Everything runs from one clock (one rAF script).

const PROMPT = COLD_OPEN.prompt.join("");
const CHAR_MS = coldOpenCharTimes();
const PASTE_MS = COLD_OPEN.pasteAt * 1000;
const ENTER_MS = COLD_OPEN.enterAt * 1000;
/** After Enter: Claude's reply, then two tool calls (COLD_OPEN.afterEnter). */
const AFTER = COLD_OPEN.afterEnter;
const SAY_MS = ENTER_MS + AFTER.say * 1000;
const TOOL1_MS = ENTER_MS + AFTER.tool1 * 1000;
const TOOL2_MS = ENTER_MS + AFTER.tool2 * 1000;
const RESULT_LAG = AFTER.resultLag * 1000;
const REPLY = "I'll turn your script into a video with Videowright.";

/** The input box's text row before Enter, and the echo's row after: the prompt stays put. */
const PROMPT_ROW = 5;
const PROMPT_CENTER_Y = rowY(PROMPT_ROW) + 23;

let host: HTMLElement | null = null;
let term: Terminal;

/** Rows of the transcript after Enter, and where the input box sits for each stage. */
interface Layout {
	spinner: number;
	input: number;
}
const AFTER_ENTER: Layout = { spinner: 7, input: 10 };
const AFTER_SAY: Layout = { spinner: 9, input: 12 };
const AFTER_TOOL1: Layout = { spinner: 12, input: 15 };
const AFTER_TOOL2: Layout = { spinner: 15, input: 18 };

const charsAt = (t: number) => {
	let n = 0;
	while (n < CHAR_MS.length && CHAR_MS[n] <= t) n++;
	return n;
};

// The camera, in three moves. Tight (1.94-1.98x, type ~62px) on the input line while the
// prompt types: the whole sentence fits, the session header above it, and a slow push keeps
// it alive. Around the paste, out to frame the full line with its chip (a cubic in-out that
// starts early, so it is settled as the chip lands); on Enter, the pull-back to the whole
// session.
const OPENING: CameraKey[] = [
	{ t: 0, x: 505, y: PROMPT_CENTER_Y, z: 1.94 },
	{ t: PASTE_MS - 330, x: 505, y: PROMPT_CENTER_Y, z: 1.98, ease: sineInOut },
	{ t: PASTE_MS + 70, x: 686, y: PROMPT_CENTER_Y - 20, z: 1.42, ease: drawEase },
	{ t: ENTER_MS, x: 686, y: PROMPT_CENTER_Y - 20, z: 1.42 },
	{ t: ENTER_MS + AFTER.pullBack * 1000, ...IDENTITY, ease: drawEase },
];
/** Script time by which the session has fully played out: every line in, camera at rest. */
const SETTLED_MS = COLD_OPEN.settledAt * 1000;

function layoutFor(t: number): Layout | null {
	if (t < ENTER_MS) return null;
	if (t < SAY_MS) return AFTER_ENTER;
	if (t < TOOL1_MS) return AFTER_SAY;
	if (t < TOOL2_MS) return AFTER_TOOL1;
	return AFTER_TOOL2;
}

function spinnerVerb(t: number): string {
	if (t < TOOL1_MS) return "Thinking…";
	if (t < TOOL2_MS) return "Writing segments…";
	return "Generating voiceover…";
}

export default defineSegment({
	id: "v2-cold-open",
	advances: [5.65, 7.33],
	voiceover:
		"The video you're watching and this voice were generated by Videowright in Claude Code, with a single prompt.",
	notes:
		"Typing and its SFX share one schedule (components/v2/typing.ts COLD_OPEN, placed by audio/audio_plan.md). Advance 1: 'Video is ready' on 'with a single prompt'. Advance 2: the hard cut, on the breath after 'prompt.'.",

	async mount(el) {
		await fontsReady();
		host = el;
		// A real screen, not the instrument: the HUD is offline until the cut.
		hideHud(el);
		term = createTerminal(el, {
			title: "videowright_demo — claude",
			version: "v2.4.0",
			model: "Opus 5.5 · Claude Max",
			cwd: "~/videowright_demo",
		});
		term.input.setRow(PROMPT_ROW);
		term.line(PROMPT_ROW + 2, `<span class="v2-faint">  ? for shortcuts</span>`);
		term.setCamera(cameraAt(OPENING, 0));
	},

	async play(ctx) {
		if (!host) return;
		const ticker: Ticker = createTicker(() => ctx.clock(), ctx.signal);
		const { input } = term;
		// The script runs on its own time, s = clock + skip. skip stays 0 in a render; in dev, an
		// early first advance (Next pressed while the prompt is still typing) jumps the script to
		// its settled end state, and "ready" and the push run from there.
		let skip = 0;
		let readyAt = Number.POSITIVE_INFINITY;
		let typed = -1;
		let entered = false;
		let stage: Layout | null = null;
		let lastKey = 0;
		let replyWords = -1;
		let spinnerHtml = "";
		const written = new Set<string>();
		const once = (key: string, at: number, s: number, write: () => void) => {
			if (s >= at && !written.has(key)) {
				written.add(key);
				write();
			}
		};
		const words = REPLY.split(" ");
		let push: CameraKey[] = [];

		ticker.add((t) => {
			const s = t + skip;
			// ── Typing (until Enter) ──
			if (s < ENTER_MS) {
				const n = charsAt(s);
				if (n !== typed) {
					typed = n;
					input.text.textContent = PROMPT.slice(0, n);
					if (n > 0) lastKey = CHAR_MS[n - 1];
				}
				once("paste", PASTE_MS, s, () => {
					input.after.innerHTML = ` ${tui.chip(COLD_OPEN.chip)}`;
					lastKey = PASTE_MS;
				});
			}

			// ── Enter: the prompt moves into the transcript; Claude works ──
			if (s >= ENTER_MS && !entered) {
				entered = true;
				input.text.textContent = "";
				input.after.textContent = "";
				term.line(PROMPT_ROW, tui.echo(PROMPT, COLD_OPEN.chip));
				lastKey = ENTER_MS;
			}
			const next = layoutFor(s);
			if (next && next !== stage) {
				if (stage) term.clear(stage.spinner);
				term.clear((stage?.input ?? PROMPT_ROW) + 2);
				stage = next;
				spinnerHtml = "";
				input.setRow(next.input);
				term.line(next.input + 2, `<span class="v2-faint">  ? for shortcuts</span>`);
			}
			once("tool1", TOOL1_MS, s, () => term.line(9, tui.tool("Skill", "videowright")));
			once("result1", TOOL1_MS + RESULT_LAG, s, () =>
				term.line(10, tui.result("Loaded new_video.md")),
			);
			once("tool2", TOOL2_MS, s, () => term.line(12, tui.tool("Write", "videos/demo_v2/PLAN.md")));
			once("result2", TOOL2_MS + RESULT_LAG, s, () =>
				term.line(13, tui.result("Wrote 8 segments, a voiceover script and a timeline")),
			);
			// Claude's reply streams in word chunks.
			if (s >= SAY_MS) {
				const shown = Math.min(words.length, 2 + Math.floor((s - SAY_MS) / 45) * 2);
				if (shown !== replyWords) {
					replyWords = shown;
					term.line(7, tui.say(words.slice(0, shown).join(" ")));
				}
			}

			// ── The spinner, until the ready cue replaces it ──
			if (stage && s < readyAt) {
				const since = s - ENTER_MS;
				// Time-lapse: the counters run ~24x, so a few seconds read as real work.
				const secs = Math.floor((since / 1000) * 24);
				const tokens = (Math.floor(since / 50) * 50 * 3.1) / 1000;
				const html = tui.spinner(
					spinnerGlyph(since),
					spinnerVerb(s),
					`${secs}s · ↓ ${tokens.toFixed(1)}k tokens · esc to interrupt`,
				);
				if (html !== spinnerHtml) {
					spinnerHtml = html;
					term.line(stage.spinner, html);
				}
			}

			// ── Caret: solid while keys are landing, blinking when idle ──
			// Once the work is done it holds solid until the cut: a blink near the cut would pull
			// the eye off the payoff line, wherever VO timing puts the cut.
			const idle = s - lastKey;
			input.caret.style.opacity =
				s >= readyAt || idle < 500 || Math.floor((idle - 500) / 530) % 2 === 1 ? "1" : "0";

			// ── Camera ──
			let cam: Camera;
			if (s < readyAt) {
				cam = cameraAt(OPENING, s);
			} else {
				if (!push.length) {
					// A push in on the payoff line, still moving near full speed when the cut lands
					// (cut on motion; past its midpoint, so easing off): at the cut the line is large
					// and central; the header has left the frame by then, its job done.
					push = [
						{ t: readyAt, ...cameraAt(OPENING, readyAt) },
						{ t: readyAt + 2600, x: 670, y: 810, z: 1.3, ease: sineInOut },
					];
				}
				cam = cameraAt(push, s);
			}
			term.setCamera(cam);
			return true;
		});

		// Cue 1 ("with a single prompt"): the work resolves.
		await ctx.waitForNext();
		const now = ticker.now();
		if (now + skip < SETTLED_MS) skip = SETTLED_MS - now;
		readyAt = now + skip;
		// The ready line replaces the spinner. A dev jump writes it after the next frame has laid
		// the settled session out, so it lands on the final layout's spinner row.
		ticker.add((t) => {
			if (t + skip < readyAt || stage !== AFTER_TOOL2) return true;
			term.line(stage.spinner, tui.say(`Video is ready. Preview: ${tui.code("npm run dev")}`));
			return false;
		});
		// play() resolves; the push holds until the final advance cuts to the title card.
	},

	unmount() {
		// Only the rAF script stops (via ctx.signal); the last frame stays as it is.
		host = null;
	},
});
